// Protocol test for the multiplayer server: two scripted players join, build,
// chat and see each other. Starts its own server with an empty world:
//   node tools/test-server.mjs
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import WebSocket from 'ws';
import { parseFrame, decodeChunkPayload, PROTOCOL } from '../js/net/protocol.js';
import { chunkKey } from '../js/world/constants.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 8800 + Math.floor(Math.random() * 600);
const DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'blockforge-srv-'));
const URL = `ws://localhost:${PORT}/ws`;
const server = spawn(process.execPath, ['server/server.js'], { cwd: ROOT, env: { ...process.env, PORT: String(PORT), DATA_DIR: DATA }, stdio: ['ignore', 'pipe', 'inherit'] });
// Never leave a server running, even if a check throws.
process.on('exit', () => server.kill('SIGKILL'));
process.on('uncaughtException', (e) => {
  console.error(e);
  process.exit(1);
});
await new Promise((resolve, reject) => {
  let out = '';
  server.stdout.on('data', (d) => {
    out += d;
    if (out.includes('Type "help"')) resolve();
  });
  server.on('exit', (code) => reject(new Error('server exited: ' + code + '\n' + out)));
});
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let failures = 0;
const check = (ok, what) => {
  console.log(`${ok ? 'PASS' : 'FAIL'} ${what}`);
  if (!ok) failures++;
};

class Bot {
  constructor(name) {
    this.name = name;
    this.msgs = [];
    this.chunks = [];
    this.key = (name + '-test-key-0123456789abcdef').replace(/[^A-Za-z0-9_-]/g, '_');
  }
  connect() {
    return new Promise((resolve, reject) => {
      this.ws = new WebSocket(URL);
      this.ws.binaryType = 'arraybuffer';
      this.ws.on('open', () => {
        this.send({ t: 'hello', v: PROTOCOL, name: this.name, key: this.key, vd: 6 });
      });
      this.ws.on('message', (data, isBinary) => {
        if (isBinary) {
          this.chunks.push(parseFrame(new Uint8Array(data)));
          return;
        }
        const m = JSON.parse(data.toString());
        for (const x of Array.isArray(m) ? m : [m]) {
          this.msgs.push(x);
          if (x.t === 'welcome') {
            this.welcome = x;
            resolve(x);
          }
          if (x.t === 'kick') {
            this.kicked = x.reason;
            resolve(null);
          }
        }
      });
      this.ws.on('close', () => (this.closed = true));
      this.ws.on('error', reject);
    });
  }
  send(m) {
    this.ws.send(JSON.stringify(m));
  }
  state(x, y, z, extra = {}) {
    this.pos = [x, y, z];
    this.send({ t: 'st', s: [x, y, z, 0, 0, 0, extra.health ?? 20, 0, 0, 0, 0, 0, 0, 0] });
  }
  find(pred) {
    return this.msgs.find(pred);
  }
  async waitFor(pred, ms = 4000) {
    const t0 = Date.now();
    while (Date.now() - t0 < ms) {
      const m = this.msgs.find(pred);
      if (m) return m;
      await sleep(25);
    }
    return null;
  }
}

const a = new Bot('Alice');
const b = new Bot('Bob');
const wa = await a.connect();
check(!!wa && wa.seed !== undefined, 'Alice gets a welcome with the world seed');
const sp = wa.spawn;
a.state(sp.x, sp.y + 1, sp.z);
a.send({ t: 'ready' });
const wb = await b.connect();
check(!!wb, 'Bob joins');
b.state(sp.x + 2, sp.y + 1, sp.z);
b.send({ t: 'ready' });
await sleep(600);
check(!!a.find((m) => m.t === 'pl' && m.l.length === 2), 'player list shows both players');
check(!!(await a.waitFor((m) => m.t === 'e' && m.s.some((s) => s.k === 'P' && s.n === 'Bob'))), 'Alice sees Bob as an entity');

// Unchanged chunks are generated by the browser. (Chunks near spawn may
// already have changed by themselves - grass spreads - so ask for one further out.)
const cx = (Math.floor(sp.x) >> 4) + 30, cz = Math.floor(sp.z) >> 4;
a.send({ t: 'req', l: [cx, cz] });
check(!!(await a.waitFor((m) => m.t === 'gen' && m.k === chunkKey(cx, cz))), 'untouched chunk: server says generate it locally');

// Wait until the server has the spawn chunk loaded, then build.
await sleep(1500);
const bx = Math.floor(sp.x) + 1, by = Math.floor(sp.y) + 3, bz = Math.floor(sp.z);
a.send({ t: 'set', x: bx, y: by, z: bz, b: 1, m: 0 });
const chg = await b.waitFor((m) => m.t === 'chg' && m.k === chunkKey(bx >> 4, bz >> 4));
check(!!chg, 'Bob is told the chunk changed');
const bs = await b.waitFor((m) => m.t === 'b' && m.l.some((v, i) => i % 5 === 0 && m.l[i] === bx && m.l[i + 1] === by && m.l[i + 2] === bz && m.l[i + 3] === 1));
check(!!bs, 'Bob receives the placed block');
b.send({ t: 'req', l: [bx >> 4, bz >> 4] });
await sleep(800);
const fr = b.chunks.find((f) => f.cx === bx >> 4 && f.cz === bz >> 4);
check(!!fr, 'changed chunk is downloaded as binary');
if (fr) {
  const d = decodeChunkPayload(fr.payload);
  check(d.blocks[(bx & 15) | ((bz & 15) << 4) | (by << 8)] === 1, 'downloaded chunk contains the new block');
}

// Far-away edits are refused and corrected.
a.send({ t: 'set', x: bx + 40, y: by, z: bz, b: 1, m: 0 });
check(!!(await a.waitFor((m) => m.t === 'b' && m.l[0] === bx + 40)), 'out-of-reach edit is corrected');

// Chat
a.send({ t: 'chat', m: 'hello bob' });
check(!!(await b.waitFor((m) => m.t === 'chat' && m.m === '<Alice> hello bob')), 'chat reaches Bob');

// Dropped items appear for everyone.
a.send({ t: 'spawn', e: { k: 'i', p: [sp.x + 4, sp.y + 2, sp.z + 4], v: [0, 0, 0], s: [1, 5, 0], d: 40 } });
check(!!(await b.waitFor((m) => m.t === 'e' && m.s.some((s) => s.k === 'i' && s.it === 1))), 'dropped item is visible to Bob');

// Commands: Alice joined first on a fresh server, so she is an operator.
a.send({ t: 'chat', m: '/time set night' });
check(!!(await b.waitFor((m) => m.t === 'time' && m.tm === 13000)), 'operator command changes time for everyone');
b.send({ t: 'chat', m: '/time set day' });
check(!!(await b.waitFor((m) => m.t === 'chat' && /operator/.test(m.m))), 'non-operator cannot use admin commands');

// Name protection
const c = new Bot('Alice');
c.key = 'someone-else-key-0123456789';
await c.connect();
check(!!c.kicked, `a different key cannot take an online name (${c.kicked})`);

// ---------------------------------------------------------------- abuse checks
// Every other spelling of an admin command still needs operator rights.
for (const c of ['/gm creative', '/teleport Alice 0 500 0', '/experience 10L', '/unban someone', '/save-all', '/op Bob']) {
  b.msgs.length = 0;
  b.send({ t: 'chat', m: c });
  const reply = await b.waitFor((m) => m.t === 'chat' && m.c === '#ff6b6b');
  check(!!reply && !b.msgs.some((m) => ['mode', 'tp', 'xpl'].includes(m.t)), `non-operator is refused: ${c}`);
}

// A huge head-turn value is cleaned up before others see it.
b.send({ t: 'st', s: [sp.x + 2, sp.y + 1, sp.z, 1e17, 0, 0, 20, 0, 0, 0, 0, 0, 0, 0] });
b.send({ t: 'st', s: [sp.x + 2.1, sp.y + 1, sp.z, 9000, 0, 0, 20, 0, 0, 0, 0, 0, 0, 0] });
await sleep(400);
const yaws = a.msgs.filter((m) => m.t === 'e').flatMap((m) => [...m.u.filter((u) => u[0] === wb.id).map((u) => u[4]), ...m.s.filter((x) => x.i === wb.id).map((x) => x.st[3])]);
check(yaws.length > 0 && yaws.every((y) => Math.abs(y) <= Math.PI + 0.01), 'yaw sent to other players stays within -pi..pi', JSON.stringify(yaws.slice(-3)));

// A death message must name its sender. (Wait for the chat rate limit to refill first.)
await sleep(2500);
b.send({ t: 'death', m: '<Alice> I am giving op to everyone' });
const dm = await a.waitFor((m) => m.t === 'chat' && /Bob died|giving op/.test(m.m));
check(!!dm && dm.m === 'Bob died', 'a fake death message is replaced', dm && dm.m);

// Deeply nested player data cannot break saving.
const deep = '['.repeat(20000) + ']'.repeat(20000);
b.ws.send(`{"t":"pd","d":{"x":1,"deep":${deep},"inventory":{"slots":[["dirt",5,0]]}}}`);
await sleep(300);
a.send({ t: 'chat', m: '/save' });
check(!!(await a.waitFor((m) => m.t === 'chat' && m.m === 'Saved the world')), 'the world still saves after junk player data');

// Prototype names are not creature types.
a.send({ t: 'chat', m: '/gamemode creative' });
await a.waitFor((m) => m.t === 'mode' && m.m === 'creative');
const before = b.msgs.length;
for (const ty of ['__proto__', 'constructor', 'toString']) a.send({ t: 'spawn', e: { k: 'm', p: [sp.x + 1, sp.y + 1, sp.z + 1], ty } });
await sleep(500);
check(!b.msgs.slice(before).some((m) => m.t === 'e' && m.s.some((x) => x.k === 'm' && ['__proto__', 'constructor', 'toString'].includes(x.ty))), 'prototype names cannot spawn broken creatures');

// Changed chunks are always served, however far away the request is.
const far = [cx + 70, cz];
a.send({ t: 'chat', m: '/gamemode survival' });
await sleep(300);
b.send({ t: 'req', l: [bx >> 4, bz >> 4] });
const servedBefore = b.chunks.length;
b.state(sp.x + 5000, sp.y + 1, sp.z);
await sleep(200);
b.send({ t: 'req', l: [bx >> 4, bz >> 4] });
await sleep(800);
check(!b.msgs.some((m) => m.t === 'gen' && m.k === chunkKey(bx >> 4, bz >> 4)), 'a changed chunk is never answered with "generate it yourself"');
void far;
void servedBefore;
b.state(sp.x + 2, sp.y + 1, sp.z);
await sleep(300);

// Two players take the same stack from one chest: only one gets it.
const chx = Math.floor(sp.x) - 1, chy = Math.floor(sp.y) + 3, chz = Math.floor(sp.z) + 1;
const { B: BL } = await import('../js/data/blocks.js');
const { I: IT } = await import('../js/data/items.js');
a.send({ t: 'set', x: chx, y: chy, z: chz, b: BL.chest, m: 0 });
await sleep(300);
a.send({ t: 'open', x: chx, y: chy, z: chz });
b.send({ t: 'open', x: chx, y: chy, z: chz });
await sleep(300);
const empty = Array(27).fill(null);
const put = empty.slice();
put[0] = [IT.diamond, 5, 0];
a.send({ t: 'tile', x: chx, y: chy, z: chz, ch: [[0, null, [IT.diamond, 5, 0]]], it: put });
await b.waitFor((m) => m.t === 'tile' && m.it && m.it[0] && m.it[0][1] === 5);
a.msgs.length = 0;
b.msgs.length = 0;
// Both now take the 5 diamonds at the same moment.
a.send({ t: 'tile', x: chx, y: chy, z: chz, ch: [[0, [IT.diamond, 5, 0], null]], it: empty });
b.send({ t: 'tile', x: chx, y: chy, z: chz, ch: [[0, [IT.diamond, 5, 0], null]], it: empty });
await sleep(600);
const untakes = [...a.msgs, ...b.msgs].filter((m) => m.t === 'untake');
check(untakes.length === 1 && untakes[0].s[1] === 5, 'taking the same stack twice gives it to only one player', JSON.stringify(untakes));

a.ws.close();
b.ws.close();
await sleep(300);
server.removeAllListeners('exit');
await new Promise((r) => {
  server.on('exit', r);
  server.kill('SIGTERM');
});
fs.rmSync(DATA, { recursive: true, force: true });
console.log(failures ? `${failures} check(s) failed` : 'All server checks passed');
process.exit(failures ? 1 : 0);

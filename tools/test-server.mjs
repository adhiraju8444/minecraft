// Protocol test for the multiplayer server: two scripted players join, build,
// chat and see each other. Starts its own server with an empty world:
//   node tools/test-server.mjs
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import WebSocket from 'ws';
import { parseFrame, decodeChunkPayload, PROTOCOL } from '../js/net/protocol.js';
import { chunkKey } from '../js/world/constants.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 8800 + Math.floor(Math.random() * 600);
const DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'blockforge-srv-'));
const URL = `ws://localhost:${PORT}/ws`;
const server = spawn(process.execPath, ['server/server.js'], { cwd: ROOT, env: { ...process.env, PORT: String(PORT), DATA_DIR: DATA }, stdio: ['ignore', 'pipe', 'inherit'] });
await new Promise((resolve, reject) => {
  let out = '';
  server.stdout.on('data', (d) => {
    out += d;
    if (out.includes('Type "help"')) resolve();
  });
  server.on('exit', (code) => reject(new Error('server exited: ' + code + '\n' + out)));
});
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let failures = 0;
const check = (ok, what) => {
  console.log(`${ok ? 'PASS' : 'FAIL'} ${what}`);
  if (!ok) failures++;
};

class Bot {
  constructor(name) {
    this.name = name;
    this.msgs = [];
    this.chunks = [];
    this.key = (name + '-test-key-0123456789abcdef').replace(/[^A-Za-z0-9_-]/g, '_');
  }
  connect() {
    return new Promise((resolve, reject) => {
      this.ws = new WebSocket(URL);
      this.ws.binaryType = 'arraybuffer';
      this.ws.on('open', () => {
        this.send({ t: 'hello', v: PROTOCOL, name: this.name, key: this.key, vd: 6 });
      });
      this.ws.on('message', (data, isBinary) => {
        if (isBinary) {
          this.chunks.push(parseFrame(new Uint8Array(data)));
          return;
        }
        const m = JSON.parse(data.toString());
        for (const x of Array.isArray(m) ? m : [m]) {
          this.msgs.push(x);
          if (x.t === 'welcome') {
            this.welcome = x;
            resolve(x);
          }
          if (x.t === 'kick') {
            this.kicked = x.reason;
            resolve(null);
          }
        }
      });
      this.ws.on('close', () => (this.closed = true));
      this.ws.on('error', reject);
    });
  }
  send(m) {
    this.ws.send(JSON.stringify(m));
  }
  state(x, y, z, extra = {}) {
    this.pos = [x, y, z];
    this.send({ t: 'st', s: [x, y, z, 0, 0, 0, extra.health ?? 20, 0, 0, 0, 0, 0, 0, 0] });
  }
  find(pred) {
    return this.msgs.find(pred);
  }
  async waitFor(pred, ms = 4000) {
    const t0 = Date.now();
    while (Date.now() - t0 < ms) {
      const m = this.msgs.find(pred);
      if (m) return m;
      await sleep(25);
    }
    return null;
  }
}

const a = new Bot('Alice');
const b = new Bot('Bob');
const wa = await a.connect();
check(!!wa && wa.seed !== undefined, 'Alice gets a welcome with the world seed');
const sp = wa.spawn;
a.state(sp.x, sp.y + 1, sp.z);
a.send({ t: 'ready' });
const wb = await b.connect();
check(!!wb, 'Bob joins');
b.state(sp.x + 2, sp.y + 1, sp.z);
b.send({ t: 'ready' });
await sleep(600);
check(!!a.find((m) => m.t === 'pl' && m.l.length === 2), 'player list shows both players');
check(!!(await a.waitFor((m) => m.t === 'e' && m.s.some((s) => s.k === 'P' && s.n === 'Bob'))), 'Alice sees Bob as an entity');

// Unchanged chunks are generated by the browser. (Chunks near spawn may
// already have changed by themselves - grass spreads - so ask for one further out.)
const cx = (Math.floor(sp.x) >> 4) + 30, cz = Math.floor(sp.z) >> 4;
a.send({ t: 'req', l: [cx, cz] });
check(!!(await a.waitFor((m) => m.t === 'gen' && m.k === chunkKey(cx, cz))), 'untouched chunk: server says generate it locally');

// Wait until the server has the spawn chunk loaded, then build.
await sleep(1500);
const bx = Math.floor(sp.x) + 1, by = Math.floor(sp.y) + 3, bz = Math.floor(sp.z);
a.send({ t: 'set', x: bx, y: by, z: bz, b: 1, m: 0 });
const chg = await b.waitFor((m) => m.t === 'chg' && m.k === chunkKey(bx >> 4, bz >> 4));
check(!!chg, 'Bob is told the chunk changed');
const bs = await b.waitFor((m) => m.t === 'b' && m.l.some((v, i) => i % 5 === 0 && m.l[i] === bx && m.l[i + 1] === by && m.l[i + 2] === bz && m.l[i + 3] === 1));
check(!!bs, 'Bob receives the placed block');
b.send({ t: 'req', l: [bx >> 4, bz >> 4] });
await sleep(800);
const fr = b.chunks.find((f) => f.cx === bx >> 4 && f.cz === bz >> 4);
check(!!fr, 'changed chunk is downloaded as binary');
if (fr) {
  const d = decodeChunkPayload(fr.payload);
  check(d.blocks[(bx & 15) | ((bz & 15) << 4) | (by << 8)] === 1, 'downloaded chunk contains the new block');
}

// Far-away edits are refused and corrected.
a.send({ t: 'set', x: bx + 40, y: by, z: bz, b: 1, m: 0 });
check(!!(await a.waitFor((m) => m.t === 'b' && m.l[0] === bx + 40)), 'out-of-reach edit is corrected');

// Chat
a.send({ t: 'chat', m: 'hello bob' });
check(!!(await b.waitFor((m) => m.t === 'chat' && m.m === '<Alice> hello bob')), 'chat reaches Bob');

// Dropped items appear for everyone.
a.send({ t: 'spawn', e: { k: 'i', p: [sp.x + 4, sp.y + 2, sp.z + 4], v: [0, 0, 0], s: [1, 5, 0], d: 40 } });
check(!!(await b.waitFor((m) => m.t === 'e' && m.s.some((s) => s.k === 'i' && s.it === 1))), 'dropped item is visible to Bob');

// Commands: Alice joined first on a fresh server, so she is an operator.
a.send({ t: 'chat', m: '/time set night' });
check(!!(await b.waitFor((m) => m.t === 'time' && m.tm === 13000)), 'operator command changes time for everyone');
b.send({ t: 'chat', m: '/time set day' });
check(!!(await b.waitFor((m) => m.t === 'chat' && /operator/.test(m.m))), 'non-operator cannot use admin commands');

// Name protection
const c = new Bot('Alice');
c.key = 'someone-else-key-0123456789';
await c.connect();
check(!!c.kicked, `a different key cannot take an online name (${c.kicked})`);

a.ws.close();
b.ws.close();
await sleep(300);
server.removeAllListeners('exit');
await new Promise((r) => {
  server.on('exit', r);
  server.kill('SIGTERM');
});
fs.rmSync(DATA, { recursive: true, force: true });
console.log(failures ? `${failures} check(s) failed` : 'All server checks passed');
process.exit(failures ? 1 : 0);
